Question _question(
  String id,
  String prompt,
  List<String> options,
  String correctAnswer,
  String subjectId,
  String topicId,
) => Question(
  id: id,
  prompt: prompt,
  type: QuestionType.multipleChoice,
  options: options,
  correctAnswer: correctAnswer,
  subjectId: subjectId,
  topicId: topicId,
);

/// Cria uma questão do tipo ligação com 5 pares.
Question _matchingQuestion(
  String id,
  String prompt,
  List<MatchingPair> pairs,
  String subjectId,
  String topicId,
) => Question(
  id: id,
  prompt: prompt,
  type: QuestionType.matching,
  options: const [],
  // Sentinela: a questão é marcada correta quando todos os pares são ligados.
  correctAnswer: '__matching_done__',
  subjectId: subjectId,
  topicId: topicId,
  pairs: pairs,
);

/// Cria uma questão de ordenação de frase.
Question _orderingQuestion(
  String id,
  String prompt,
  List<String> words,
  String correctAnswer,
  String subjectId,
  String topicId,
) => Question(
  id: id,
  prompt: prompt,
  type: QuestionType.ordering,
  options: words,
  correctAnswer: correctAnswer,
  subjectId: subjectId,
  topicId: topicId,
);
